"""Bridge to PQE: Diamond findings become PQE findings and regression tests.

The loop this closes: a problem found once by a human must never come back.
Deterministic finding types are turned into Playwright (Python) tests that
PQE's UI runner can execute on every push.
"""

from __future__ import annotations

import json
from typing import Any

from ..model import Category, Finding

PQE_DIMENSION = {
    Category.VISUAL: "UI_VISUAL", Category.LAYOUT: "UI_VISUAL", Category.CONSISTENCY: "UI_VISUAL",
    Category.INTERACTION: "UI_INTERACTION", Category.ANIMATION: "PERFORMANCE", Category.PERFORMANCE: "PERFORMANCE",
    Category.ACCESSIBILITY: "ACCESSIBILITY", Category.RTL: "UI_VISUAL", Category.CONTENT: "UI_VISUAL",
    Category.RUNTIME: "E2E_FLOW", Category.ARCHITECTURE: "ARCHITECTURE", Category.OTHER: "UI_VISUAL",
}


def to_pqe(findings: list[Finding]) -> list[dict[str, Any]]:
    out = []
    for f in findings:
        src = f.sources[0] if f.sources else None
        out.append({
            "check_id": f"diamond.{f.check_id}",
            "dimension": PQE_DIMENSION[f.category],
            "severity": f.severity.value,
            "title": f.title,
            "detail": f.detail or f.utterance,
            "location": {"path": src.path, "line": src.line} if src else None,
            "evidence": {**f.evidence, "page_url": f.page_url, "selector": (f.target or {}).get("selector"),
                         "origin": f.origin.value, "diamond_id": f.fingerprint},
            "suggestion": f.suggestion,
        })
    return out


_HEADER = '''"""Regression tests generated by Diamond from a review session.

Each test pins one problem a reviewer (or Diamond) found, so it cannot return.
Run with PQE's UI runner or directly:  pytest <this file>  (needs pytest-playwright).
Set DIAMOND_BASE_URL to point at another environment.
"""

import os

import pytest

BASE = os.environ.get("DIAMOND_BASE_URL", "")


def _url(recorded: str) -> str:
    if not BASE:
        return recorded
    from urllib.parse import urlsplit
    parts = urlsplit(recorded)
    return BASE.rstrip("/") + parts.path + (("?" + parts.query) if parts.query else "")


_CONTRAST_JS = """(el) => {
  const p = (c) => (c.match(/[\\\\d.]+/g) || []).map(Number);
  const lum = ([r, g, b]) => [r, g, b].map(v => { v /= 255; return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; })
      .reduce((a, v, i) => a + v * [0.2126, 0.7152, 0.0722][i], 0);
  let bg = null;
  for (let n = el; n && !bg; n = n.parentElement) { const c = p(getComputedStyle(n).backgroundColor); if (c.length && (c[3] ?? 1) > 0.5) bg = c; }
  bg = bg || [255, 255, 255];
  const [a, b] = [lum(p(getComputedStyle(el).color)), lum(bg)].sort((x, y) => y - x);
  return (a + 0.05) / (b + 0.05);
}"""
'''


def _test_for(f: Finding) -> str | None:
    selector = (f.target or {}).get("selector")
    url = f.page_url
    name = f"test_{f.check_id.replace('.', '_')}_{f.fingerprint}"
    if f.check_id == "rtl.page_direction":
        return (f"def {name}(page):\n    page.goto(_url({url!r}))\n"
                f"    assert page.evaluate(\"document.documentElement.dir || getComputedStyle(document.body).direction\") == 'rtl'\n")
    if not selector:
        return None
    sel = json.dumps(selector)
    if f.check_id == "a11y.contrast":
        need = f.evidence.get("threshold", 4.5)
        return (f"def {name}(page):\n    page.goto(_url({url!r}))\n"
                f"    ratio = page.locator({sel}).first.evaluate(_CONTRAST_JS)\n    assert ratio >= {need}, ratio\n")
    if f.check_id == "a11y.target_size":
        return None  # multiple elements; covered by PQE's axe run
    if f.check_id == "a11y.accessible_name":
        return (f"def {name}(page):\n    page.goto(_url({url!r}))\n    el = page.locator({sel}).first\n"
                f"    assert (el.get_attribute('aria-label') or el.inner_text()).strip()\n")
    if f.check_id == "interaction.dead_click":
        return (f"def {name}(page):\n    page.goto(_url({url!r}))\n    before = page.evaluate('document.body.innerHTML.length'), page.url\n"
                f"    page.locator({sel}).first.click()\n    page.wait_for_timeout(1000)\n"
                f"    assert (page.evaluate('document.body.innerHTML.length'), page.url) != before, 'click had no visible effect'\n")
    return None


def regression_tests(findings: list[Finding]) -> str | None:
    bodies = [t for f in findings if (t := _test_for(f))]
    if not bodies:
        return None
    return _HEADER + "\n\n" + "\n\n".join(bodies)
