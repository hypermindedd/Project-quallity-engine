"""Turn a discovered profile into a *draft* quality contract.

The draft is deliberately conservative: it enables only checks that can run
from what discovery saw, and it leaves goal-to-evidence mapping as explicit
TODO goals that report UNVERIFIED until a human (or the onboarding skill)
completes them. Nothing is marked as met by default.
"""

from __future__ import annotations

import json

from .profile import ProjectProfile


def _s(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _list(values: list[str]) -> str:
    return "[" + ", ".join(_s(v) for v in values) + "]"


def draft_contract(profile: ProjectProfile) -> str:
    goal = profile.goal_statements[0].split(": ", 1)[-1] if profile.goal_statements else ""
    docs = sorted({d.path.split("/")[0] + "/**/*.md" if "/" in d.path else d.path for d in profile.docs})[:12]
    out: list[str] = [
        "# Project Quality Engine contract (DRAFT — generated by `pqe init`).",
        "# Review every section. Goals below are UNVERIFIED until mapped to real evidence.",
        "",
        "[project]",
        f"name = {_s(profile.name)}",
        f"goal = {_s(goal)}",
        f"docs = {_list(docs)}",
        "exclude = []",
        "",
    ]
    python = "python" in profile.languages
    out += ["[pytest]", f"enabled = {'true' if python and profile.test_dirs else 'false'}", ""]

    for folder, scripts in sorted(profile.node_projects.items()):
        prefix = "" if folder in {"", "."} else folder.replace("/", "-") + "-"
        for script in ("typecheck", "lint", "test", "build"):
            if script in scripts:
                title = f"{folder or '.'}: npm run {script}"
                out += [
                    "[[commands]]",
                    f"id = {_s(prefix + script)}",
                    f"title = {_s(title)}",
                    f"argv = {_list(['npm', 'run', script])}",
                    f"cwd = {_s(folder or '.')}",
                    f"dimension = {_s('FUNCTIONAL' if script == 'test' else 'CODE_QUALITY' if script == 'lint' else 'BUILD')}",
                    f"requires = {_list([(folder + '/' if folder not in {'', '.'} else '') + 'node_modules'])}",
                    "",
                ]

    out += ["[architecture]", f"python_roots = {_list(profile.python_roots)}", "detect_cycles = true", ""]
    out += [
        "# Declare boundaries from the architecture documents, e.g.:",
        "# [[architecture.rules]]",
        '# name = "domain-independent-of-web"',
        '# source = "mypkg.domain"',
        '# forbid = ["mypkg.web", "fastapi"]',
        '# reason = "Domain logic must not depend on the delivery layer (docs/ARCHITECTURE.md)"',
        "",
    ]
    node_dirs = sorted({lf.rsplit("/", 1)[0] if "/" in lf else "." for lf in profile.lockfiles if lf.endswith(("pnpm-lock.yaml", "package-lock.json"))})
    out += ["[security]", "secrets = true", "bandit = true", "pip_audit = true", f"npm_audit_dirs = {_list(node_dirs)}", ""]

    if profile.app_entrypoints:
        out += [
            "# API verification: the engine boots an isolated instance and probes it.",
            "[api]",
            "enabled = false  # set true after filling start_command / endpoints",
            f"# detected app entrypoints: {', '.join(profile.app_entrypoints[:5])}",
            '# start_command = ["python", "-m", "uvicorn", "pkg.module:app", "--port", "{port}"]',
            "",
        ]
    if any(f in profile.frameworks for f in ("next", "react", "vue", "svelte", "vite")):
        out += [
            "[ui]",
            "enabled = false  # set true with a start_command or test base_url",
            "",
        ]

    out += [
        "[[goals]]",
        'id = "G-00"',
        'title = "The full automated test suite passes"',
        "hard_gate = true",
        "criteria = [{ kind = \"check\", check = \"functional.*\" }]",
        "",
    ]
    for prefix, info in sorted(profile.requirement_families.items(), key=lambda kv: -int(kv[1]["distinct_ids"])):
        family_title = f"Requirements {prefix}-* are verified ({info['distinct_ids']} found)"
        out += [
            "# TODO: map each requirement of this family to evidence, then list the IDs in 'covers'.",
            "[[goals]]",
            f"id = {_s('G-' + prefix)}",
            f"title = {_s(family_title)}",
            f"source = {_s(', '.join(info['defined_in']))}",  # type: ignore[arg-type]
            "covers = []",
            f"criteria = [{{ kind = \"attestation\", attestation = {_s('TODO-' + prefix)} }}]",
            "",
        ]
    return "\n".join(out)
